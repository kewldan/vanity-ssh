#!/usr/bin/env bash
# Embeds Sources/VanitySSH/Metal/Kernel.metal into a Swift string so that the
# release is a single self-contained binary.
#
#   scripts/embed-kernel.sh          regenerate KernelSource.swift
#   scripts/embed-kernel.sh --check  fail if KernelSource.swift is stale
set -euo pipefail

cd "$(dirname "$0")/.."
src="Sources/VanitySSH/Metal/Kernel.metal"
dst="Sources/VanitySSH/KernelSource.swift"

if grep -q '"""#' "$src"; then
  echo "error: $src must not contain the raw string terminator" >&2
  exit 1
fi

generate() {
  printf '%s\n' \
    '// swift-format-ignore-file' \
    "// Generated by scripts/embed-kernel.sh from $src. Do not edit." \
    '' \
    'enum KernelSource {' \
    '  static let text = #"""'
  cat "$src"
  printf '%s\n' '"""#' '}'
}

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -q <(generate) "$dst" >/dev/null 2>&1; then
    echo "error: $dst is stale; run scripts/embed-kernel.sh" >&2
    exit 1
  fi
else
  generate >"$dst"
fi
